#!/usr/bin/env node
// Generates the desktop auto-update manifest (electron-updater YAML) that
// ZCode Local builds poll from our GitHub releases. Attach the output as the
// `electron-manifest.yml` asset of any release that ships desktop installers.
// Releases without desktop binaries publish no manifest: the updater treats a
// missing manifest as "already up to date".
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const LOCAL_UPDATE_BASE_URL =
  "https://github.com/Franzferdinan51/ZCode/releases/latest/download/";
const usage = `Usage:
  node scripts/build-electron-manifest.mjs --version 3.15.0
  node scripts/build-electron-manifest.mjs --asset "ZCode-Local-3.15.0.dmg:<sha512>"

Options:
  --version <text>         Manifest version. Defaults to root package.json version.
  --out <path>             Output file. Defaults to dist/zcode/electron-manifest.yml.
  --asset-base-url <url>   Base URL for file entries. Defaults to our latest
                           GitHub release download URL; pass the release tag URL
                           for a pinned, reproducible manifest.
  --asset <name:sha512>    Repeatable desktop installer asset attached to the
                           release. File URLs are emitted absolute: the updater
                           resolves relative paths against https://github.com/.
  --help, -h               Show this help.
`;

function readArgValue(argv, arg, index) {
  if (arg.includes("=")) {
    return { nextIndex: index, value: arg.slice(arg.indexOf("=") + 1) };
  }
  const value = argv[index + 1];
  if (!value || value.startsWith("--")) {
    throw new Error(`Missing value for ${arg}`);
  }
  return { nextIndex: index + 1, value };
}

function parseArgs(argv) {
  const options = {
    assetBaseUrl: LOCAL_UPDATE_BASE_URL,
    assets: [],
    help: false,
    out: resolve(root, "dist/zcode/electron-manifest.yml"),
    version: undefined,
  };
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === "--") continue;
    if (arg === "--help" || arg === "-h") {
      options.help = true;
      continue;
    }
    if (arg === "--version" || arg.startsWith("--version=")) {
      const { nextIndex, value } = readArgValue(argv, arg, index);
      options.version = value;
      index = nextIndex;
      continue;
    }
    if (arg === "--out" || arg.startsWith("--out=")) {
      const { nextIndex, value } = readArgValue(argv, arg, index);
      options.out = resolve(root, value);
      index = nextIndex;
      continue;
    }
    if (arg === "--asset-base-url" || arg.startsWith("--asset-base-url=")) {
      const { nextIndex, value } = readArgValue(argv, arg, index);
      options.assetBaseUrl = value.endsWith("/") ? value : `${value}/`;
      index = nextIndex;
      continue;
    }
    if (arg === "--asset" || arg.startsWith("--asset=")) {
      const { nextIndex, value } = readArgValue(argv, arg, index);
      options.assets.push(value);
      index = nextIndex;
      continue;
    }
    throw new Error(`Unknown option "${arg}". Run with --help for usage.`);
  }
  return options;
}

function parseAsset(spec) {
  const separator = spec.indexOf(":");
  const name = separator < 0 ? "" : spec.slice(0, separator).trim();
  const sha512 = separator < 0 ? "" : spec.slice(separator + 1).trim();
  if (!name || /[\\/\\s]/.test(name)) {
    throw new Error(`Invalid --asset name in "${spec}": expected a bare file name.`);
  }
  if (!/^[0-9a-fA-F]{128}$/.test(sha512)) {
    throw new Error(`Invalid --asset sha512 in "${spec}": expected 128 hex chars.`);
  }
  return { name, sha512: sha512.toLowerCase() };
}

function renderManifest({ version, assetBaseUrl, assets }) {
  const lines = [
    "# Generated by scripts/build-electron-manifest.mjs — do not edit by hand.",
    `version: ${version}`,
    `releaseDate: '${new Date().toISOString()}'`,
  ];
  if (assets.length > 0) {
    lines.push("files:");
    for (const asset of assets) {
      lines.push(`  - url: ${assetBaseUrl}${asset.name}`);
      lines.push(`    sha512: ${asset.sha512}`);
    }
  }
  return `${lines.join("\n")}\n`;
}

async function main() {
  const options = parseArgs(process.argv.slice(2));
  if (options.help) {
    console.log(usage);
    return;
  }
  const version =
    options.version ?? JSON.parse(await readFile(resolve(root, "package.json"), "utf8")).version;
  if (!version || !/^\d+\.\d+\.\d+([-+][0-9A-Za-z.-]+)?$/.test(version)) {
    throw new Error(`Invalid version "${version}": expected semver like 3.15.0.`);
  }
  const assets = options.assets.map(parseAsset);
  await mkdir(dirname(options.out), { recursive: true });
  await writeFile(options.out, renderManifest({ version, assetBaseUrl: options.assetBaseUrl, assets }));
  console.log(`[manifest] ${options.out} version=${version} files=${assets.length}`);
}

await main();
